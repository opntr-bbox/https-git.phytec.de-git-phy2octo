import itertools

class phyKernel:
    """
    PHYTEC linux production kernel class: specification of every component responsible for a new kernel branch
    """

    'Kernel ID generator'
    newKID = itertools.count().next

    def __init__(self, version, patchlevel, sublevel):
        self.version = version
        self.patchlevel = patchlevel
        self.sublevel = sublevel
        self.extraversion = 0

        'location of the kernel'
        self.giturl = "http://"
        self.branchname = "testbranch"
        'each kernel may have a location of a (quilt) patch stack'
        self.patchstackurl = "git://"

        'Kernel ID'
        self.kid = phyKernel.newKID()



class TIKernel(phyKernel):
    """
    all linux kernels from texas instruments will inherit this class
    """

class FSLKernel(phyKernel):
    """
    all linux kernels from freescale will inherit this class
    """

class MainlineKernel(phyKernel):
    """
    all mainline linux kernels will inherit this class
    """

